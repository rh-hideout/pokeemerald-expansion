#!/usr/bin/env python3
"""Build-time localization tool.

    loc.py extract [--prune]              scan sources, create/update CSVs
    loc.py seed LANG [--copy-src|--pseudo] add a language column (optionally filled)
    loc.py generate --lang LANG --out DIR emit preproc tables + graphics overlay (validates)
    loc.py validate --lang LANG|all       validate without writing build outputs
    loc.py stats                          translation coverage per language
    loc.py audit-concat                   list code that builds sentences from fragments

See localization/README.md.
"""

import argparse
import os
import re
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import csvstore  # noqa: E402
import extract   # noqa: E402
from charmap import Charmap, tokenize  # noqa: E402
from fonts import FONTS, FontSet  # noqa: E402
from generate import generate  # noqa: E402
from project import ASSETS_CSV, CHARMAP_PATH, TEXT_DIR, Project  # noqa: E402

DEFAULT_CACHE = os.path.join("build", "loc", "scan_cache.pickle")


def load_tools(project):
    charmap = Charmap(project.path(CHARMAP_PATH))
    fonts = FontSet(project.root, charmap, project.rules.get("placeholder_chars", {}))
    return charmap, fonts


def all_csvs(project):
    out = []
    for dirpath, _, files in os.walk(project.path(TEXT_DIR)):
        for name in sorted(files):
            if name.endswith(".csv"):
                out.append(os.path.join(dirpath, name))
    if os.path.exists(project.path(ASSETS_CSV)):
        out.append(project.path(ASSETS_CSV))
    return sorted(out)


# ---------------------------------------------------------------------------
def cmd_extract(project, args):
    scans = extract.scan_all(project, cache_path=project.path(DEFAULT_CACHE))
    if project.missing_generated:
        print("loc extract: error: generated sources are missing (run 'make generated' first): "
              + ", ".join(project.missing_generated), file=sys.stderr)
        return 1
    totals = {"added": 0, "changed": 0, "carried": 0, "obsolete": 0, "removed": 0}
    files_changed = 0
    units = 0
    skipped = []
    for rel, scan in sorted(scans.items()):
        units += len(scan.units)
        skipped += [(rel, line, reason) for line, reason in scan.skipped]
        stats, changed = extract.update_csv(project, rel, scan.units, prune=args.prune)
        files_changed += changed
        for k, v in stats.items():
            totals[k] += v
    removed = extract.remove_orphan_csvs(project, scans)
    report = project.path(TEXT_DIR, "_skipped.txt")
    lines = ["# Strings found in the sources that cannot be localized by key.\n",
             "# Generated by 'make loc-extract'; do not edit.\n"]
    lines += [f"{rel}:{line}: {reason}\n" for rel, line, reason in sorted(skipped)]
    csvstore.write_if_changed(report, "".join(lines))
    print(f"loc extract: {units} units in {len(scans)} files; "
          f"{totals['added']} added, {totals['changed']} changed (marked stale where translated), "
          f"{totals['carried']} translations carried over to renamed keys, "
          f"{totals['obsolete']} newly obsolete, {totals['removed']} removed; "
          f"{files_changed} CSV files written, {len(removed)} orphan CSVs deleted; "
          f"{len(skipped)} strings skipped (see {project.rel(report)})")
    return 0


PSEUDO_PAIRS = list(zip("aeiouAEIOUnNcC", "áéíóúÁÉÍÓÚñÑçÇ"))


def pseudo_map(charmap, fonts):
    """Accents that are no wider than their base letter in any font, so the
    pseudo-locale passes width validation."""
    table = {}
    for base, accented in PSEUDO_PAIRS:
        a = charmap.chars.get(base)
        b = charmap.chars.get(accented)
        if not a or not b:
            continue
        if all(fonts.glyph_width(f, b[0]) <= fonts.glyph_width(f, a[0]) for f in FONTS):
            table[base] = accented
    return table


def pseudo(text, table):
    out = []
    for tok in tokenize(text):
        out.append(tok if tok.startswith(("{", "\\")) else table.get(tok, tok))
    return "".join(out)


def cmd_seed(project, args):
    lang = args.lang
    if lang not in project.languages:
        print(f"loc seed: unknown language '{lang}'; add it to localization/rules.json first", file=sys.stderr)
        return 1
    src = project.source_language
    filled = 0
    table = pseudo_map(*load_tools(project)) if args.pseudo else None
    for path in all_csvs(project):
        header, rows = csvstore.read_csv(path)
        if header is None:
            continue
        header = csvstore.ensure_languages(header, project.languages)
        for row in rows:
            if args.copy_src or args.pseudo:
                if not row.get(lang) or args.force:
                    status = csvstore.parse_status(row.get("status"))
                    if "obsolete" in status:
                        continue
                    row[lang] = pseudo(row.get(src, ""), table) if args.pseudo else row.get(src, "")
                    filled += 1
        csvstore.write_if_changed(path, csvstore.render_csv(header, rows))
    print(f"loc seed: '{lang}' column present in all CSVs; {filled} cells filled")
    return 0


def print_diagnostics(validator, verbose, limit=40):
    errors = validator.errors
    warnings = validator.warnings
    for d in errors:
        print(d.format(), file=sys.stderr)
    shown = warnings if verbose else warnings[:limit]
    for d in shown:
        print(d.format(), file=sys.stderr)
    if len(shown) < len(warnings):
        print(f"... {len(warnings) - len(shown)} more warnings (LOC_VERBOSE=1 to show all)", file=sys.stderr)


def write_report(path, lang, result, validator):
    lines = [f"Localization report for '{lang}'\n",
             f"translated: {result.translated}/{result.total}\n",
             f"errors: {len(validator.errors)}  warnings: {len(validator.warnings)}\n\n"]
    lines += [d.format() + "\n" for d in validator.diagnostics]
    if result.missing:
        lines.append("\nMissing translations:\n")
        lines += [f"{project_csv}: {key}\n" for project_csv, key in result.missing]
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.writelines(lines)


def run_generate(project, lang, out_dir, strict, verbose):
    if lang not in project.languages:
        print(f"loc: unknown language '{lang}' (known: {', '.join(project.languages)})", file=sys.stderr)
        return 1
    charmap, fonts = load_tools(project)
    scans = extract.scan_all(project, cache_path=project.path(DEFAULT_CACHE))
    result, validator = generate(project, charmap, fonts, lang, out_dir, strict=strict, scans=scans)
    print_diagnostics(validator, verbose)
    write_report(os.path.join(out_dir, "report.txt"), lang, result, validator)
    pct = 100.0 * result.translated / result.total if result.total else 100.0
    missing = len(result.missing)
    status = "FAILED" if validator.errors else "ok"
    print(f"loc [{lang}]: {result.translated}/{result.total} strings translated ({pct:.1f}%), "
          f"{missing} fall back to {project.source_language}, {len(result.graphics)} localized graphics; "
          f"{len(validator.errors)} errors, {len(validator.warnings)} warnings -> {status}")
    return 1 if validator.errors else 0


def cmd_generate(project, args):
    return run_generate(project, args.lang, os.path.abspath(args.out), args.strict, args.verbose)


def cmd_validate(project, args):
    langs = project.target_languages if args.lang == "all" else [args.lang]
    rc = 0
    with tempfile.TemporaryDirectory() as tmp:
        for lang in langs:
            rc |= run_generate(project, lang, os.path.join(tmp, lang), args.strict, args.verbose)
    return rc


def cmd_stats(project, args):
    counts = {l: 0 for l in project.target_languages}
    stale = {l: 0 for l in project.target_languages}
    total = 0
    for path in all_csvs(project):
        _, rows = csvstore.read_csv(path)
        for row in rows:
            status = csvstore.parse_status(row.get("status"))
            if "obsolete" in status:
                continue
            total += 1
            for l in counts:
                if row.get(l):
                    counts[l] += 1
                if l in status.get("stale", set()):
                    stale[l] += 1
    print(f"{total} keys")
    for l in counts:
        pct = 100.0 * counts[l] / total if total else 0
        name = project.languages[l].get("name", l)
        print(f"  {l} ({name}): {counts[l]} translated ({pct:.1f}%), {stale[l]} stale")
    return 0


CONCAT_RE = re.compile(r"\b(StringCopy|StringAppend|StringExpandPlaceholders|StringCopyN)\s*\(\s*([^,]+?)\s*,\s*([^;]*?)\)\s*;")


def cmd_audit_concat(project, args):
    """Reports buffers built by appending several localizable fragments."""
    findings = 0
    for kind, rel in project.source_files():
        if kind != "c":
            continue
        with open(project.path(rel), encoding="utf-8") as f:
            lines = f.read().split("\n")
        run = []
        for idx, line in enumerate(lines, 1):
            m = CONCAT_RE.search(line)
            if m:
                fn, dst, src = m.groups()
                localized = bool(re.search(r"\b[gs]Text_\w+|COMPOUND_STRING|\b_\(", src))
                if run and run[-1][1] == dst and fn in ("StringAppend",):
                    run.append((idx, dst, src, localized))
                else:
                    if len(run) > 1 and sum(r[3] for r in run) >= 1:
                        findings += 1
                        print(f"{rel}:{run[0][0]}: {len(run)} fragments appended into {run[0][1]}: "
                              + " + ".join(r[2] for r in run))
                    run = [(idx, dst, src, localized)] if fn in ("StringCopy", "StringExpandPlaceholders") else []
            elif line.strip() and not line.strip().startswith(("//", "case", "break", "{", "}", "else", "if")):
                if len(run) > 1 and sum(r[3] for r in run) >= 1:
                    findings += 1
                    print(f"{rel}:{run[0][0]}: {len(run)} fragments appended into {run[0][1]}: "
                          + " + ".join(r[2] for r in run))
                run = []
    print(f"loc audit-concat: {findings} sentence(s) assembled from fragments; consider one "
          "translatable string with {{STR_VAR_n}} placeholders and StringExpandPlaceholders()", file=sys.stderr)
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("extract", help="scan sources and update localization/text/**.csv")
    p.add_argument("--prune", action="store_true", help="delete rows for keys that no longer exist")
    p.set_defaults(func=cmd_extract)

    p = sub.add_parser("seed", help="add a language column to every CSV")
    p.add_argument("lang")
    g = p.add_mutually_exclusive_group()
    g.add_argument("--copy-src", action="store_true", help="fill empty cells with the source text")
    g.add_argument("--pseudo", action="store_true", help="fill empty cells with accented pseudo-text")
    p.add_argument("--force", action="store_true", help="overwrite non-empty cells too")
    p.set_defaults(func=cmd_seed)

    p = sub.add_parser("generate", help="emit build inputs for one language")
    p.add_argument("--lang", required=True)
    p.add_argument("--out", required=True)
    p.add_argument("--strict", action="store_true", help="treat missing/stale translations as errors")
    p.add_argument("-v", "--verbose", action="store_true")
    p.set_defaults(func=cmd_generate)

    p = sub.add_parser("validate", help="validate translations without writing build outputs")
    p.add_argument("--lang", default="all")
    p.add_argument("--strict", action="store_true")
    p.add_argument("-v", "--verbose", action="store_true")
    p.set_defaults(func=cmd_validate)

    p = sub.add_parser("stats", help="translation coverage")
    p.set_defaults(func=cmd_stats)

    p = sub.add_parser("audit-concat", help="list sentences assembled from fragments")
    p.set_defaults(func=cmd_audit_concat)

    args = parser.parse_args(argv)
    project = Project()
    os.chdir(project.root)
    try:
        return args.func(project, args)
    except csvstore.CsvError as e:
        print(f"loc: error: {e}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
